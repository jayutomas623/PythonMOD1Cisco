#Programa: Area de un rectangulo

# Tema: Entrada de datos y operaciones basicas

# 1. Pedimos la base y la altura

base = float(input("Ingrese la base: "))
altura = float(input("Ingrese la altura: "))

# 2. Calculamos el area base*altura
area = base * altura

print(f"la area del rectangulo es: {area}")

print(f"El area del rectangulo es: {area:.2f}")