#Conversion de tipos

# 1. Diferentes tipos de datos

texto = "123"

# 2. Mostramos el valor original

print(f"Valor original {texto} y su tipo de dato es {type(texto)}")

# 3. Convertimos el tipo a un entero

valor_convertido =  int(texto)

# 4. Mostramos el valor convertido

print(f"Valor convertido {valor_convertido} y su tipo de dato es {type(valor_convertido)}")