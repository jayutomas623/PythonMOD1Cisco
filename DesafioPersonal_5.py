# Conversion de tipos de variables

#Declaramos la variable
a = "123"

#Mostramos el tipo de dato de la variable
print(f"La variable a esta almacenando un dato de tipo: {type(a)}")

#Cambiamos su formatop y lo almacenamos en otra variable
convertido = int(a)

# Mostramos la variable que almacena lo convertido
print(f"La variable \"convertido\" esta almacenando ahora el dato convertido de a y el tipo de dato es: {type(convertido)}")
